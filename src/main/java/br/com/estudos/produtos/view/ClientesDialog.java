    @Override
    public void mostrarDados(String nome, String logradouro, String bairro,
            String cidade, String uf, String tipo, String totalCompras) {
        textFieldNome.setText(nome);
        textFieldLogradouro.setText(logradouro);
        textFieldBairro.setText(bairro);
        textFieldCidade.setText(cidade);
        textFieldUf.setText(uf);
        textFieldTipo.setText(tipo);
        textFieldTotalCompras.setText(totalCompras);
    }

    @Override
    public void mostrarClientes(String[][] linhas) {
        Tabelas.preencher(tableClientes, linhas);
    }

    @Override
    public void selecionarLinha(int indice) {
        if (indice < 0) {
            tableClientes.clearSelection();
        } else {
            tableClientes.setRowSelectionInterval(indice, indice);
        }
    }

    @Override
    public void definirModo(boolean editando, boolean selecionado, String descricao) {
        labelModo.setText("Modo: " + descricao);

        textFieldNome.setEditable(editando);
        textFieldLogradouro.setEditable(editando);
        textFieldBairro.setEditable(editando);
        textFieldCidade.setEditable(editando);
        textFieldUf.setEditable(editando);
        tableClientes.setEnabled(!editando);

        btnNovo.setEnabled(!editando);
        btnFechar.setEnabled(!editando);
        btnEditar.setEnabled(!editando && selecionado);
        btnExcluir.setEnabled(!editando && selecionado);
        btnSalvar.setEnabled(editando);
        btnCancelar.setEnabled(editando);

        if (editando) {
            textFieldNome.requestFocusInWindow();
        }

        setDefaultCloseOperation(editando ? javax.swing.WindowConstants.DO_NOTHING_ON_CLOSE
                : javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
    }

